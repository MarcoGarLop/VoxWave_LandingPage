export const clamp = (v: number, a = 0, b = 1) => Math.min(b, Math.max(a, v));
export const lerp = (a: number, b: number, t: number) => a + (b - a) * t;
export const smoothstep = (e0: number, e1: number, x: number) => {
  const t = clamp((x - e0) / (e1 - e0));
  return t * t * (3 - 2 * t);
};

/**
 * Cubic-bezier easing (CSS semantics). Solved with Newton iterations,
 * accurate enough for animation and cheap to evaluate per point.
 */
export function bezier(x1: number, y1: number, x2: number, y2: number) {
  const cx = 3 * x1;
  const bx = 3 * (x2 - x1) - cx;
  const ax = 1 - cx - bx;
  const cy = 3 * y1;
  const by = 3 * (y2 - y1) - cy;
  const ay = 1 - cy - by;
  const sx = (t: number) => ((ax * t + bx) * t + cx) * t;
  const sy = (t: number) => ((ay * t + by) * t + cy) * t;
  const dx = (t: number) => (3 * ax * t + 2 * bx) * t + cx;
  return (x: number) => {
    if (x <= 0) return 0;
    if (x >= 1) return 1;
    let t = x;
    for (let i = 0; i < 6; i++) {
      const d = dx(t);
      if (Math.abs(d) < 1e-6) break;
      t -= (sx(t) - x) / d;
    }
    return sy(clamp(t));
  };
}

/** The pitch-wide curve: cubic-bezier(.22, 1, .36, 1). */
export const easeOut = bezier(0.22, 1, 0.36, 1);
/** Symmetric curve for shape-to-shape morphs (no abrupt start). */
export const easeInOut = bezier(0.65, 0, 0.35, 1);

/** Design-space (px from top-left) to world-space (origin at centre, y up). */
export const toWorldX = (x: number) => x - 960;
export const toWorldY = (y: number) => 540 - y;
